// Fallback to English for languages without full translations
Object.keys(LANGUAGES).forEach(code => {
  if (!TRANSLATIONS[code]) TRANSLATIONS[code] = TRANSLATIONS.en;
});

function getT(key) {
  const lang = (typeof cfg !== 'undefined' && cfg.uiLang) ? cfg.uiLang : 'de';
  const t = TRANSLATIONS[lang] || TRANSLATIONS.de;
  return t[key] || TRANSLATIONS.de[key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = getT(key);
    if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = getT(key);
  });
  // Also update html lang attribute
  const lang = (typeof cfg !== 'undefined' && cfg.uiLang) ? cfg.uiLang : 'de';
  document.documentElement.lang = lang;
}
